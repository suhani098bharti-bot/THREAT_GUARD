"""Database schema initialization and administrative setup for ThreatGuard."""

import logging
from pathlib import Path
from typing import Optional, Union

from authentication.password_utils import hash_password
from config.settings import (
    DATABASE_PATH,
    INITIAL_ADMIN_PASSWORD,
    INITIAL_ADMIN_ROLE,
    INITIAL_ADMIN_USERNAME,
)
from database.db_connection import get_db_connection

logger = logging.getLogger("threatguard.db_setup")


SCHEMA_SQL = """
-- Users table for RBAC (Admin, Analyst)
CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('Admin', 'Analyst')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Security event logs ingested from CSV/JSON
CREATE TABLE IF NOT EXISTS security_logs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    timestamp TEXT NOT NULL,
    source_ip TEXT NOT NULL,
    destination_ip TEXT,
    username TEXT,
    event_type TEXT NOT NULL,
    status TEXT NOT NULL,
    port INTEGER,
    protocol TEXT,
    message TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Security incidents generated by detection engine or analysts
CREATE TABLE IF NOT EXISTS incidents (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    source_ip TEXT,
    severity TEXT NOT NULL CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    risk_score INTEGER NOT NULL CHECK (risk_score >= 0 AND risk_score <= 100),
    description TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'New' CHECK (status IN ('New', 'Investigating', 'Contained', 'Resolved', 'False Positive')),
    assigned_to TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    resolution_notes TEXT
);

-- Granular detection events matching rule criteria linked to incidents
CREATE TABLE IF NOT EXISTS detection_events (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    rule_id TEXT NOT NULL,
    incident_id INTEGER,
    source_ip TEXT,
    severity TEXT NOT NULL,
    risk_score INTEGER NOT NULL,
    explanation TEXT NOT NULL,
    detected_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(incident_id) REFERENCES incidents(id) ON DELETE CASCADE
);

-- Analyst notes and audit trail for incidents
CREATE TABLE IF NOT EXISTS incident_notes (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    incident_id INTEGER NOT NULL,
    user_id INTEGER,
    username TEXT NOT NULL,
    note TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(incident_id) REFERENCES incidents(id) ON DELETE CASCADE,
    FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- System Indexes for performant SIEM analytics
CREATE INDEX IF NOT EXISTS idx_logs_source_ip ON security_logs(source_ip);
CREATE INDEX IF NOT EXISTS idx_logs_timestamp ON security_logs(timestamp);
CREATE INDEX IF NOT EXISTS idx_logs_event_type ON security_logs(event_type);
CREATE INDEX IF NOT EXISTS idx_incidents_severity ON incidents(severity);
CREATE INDEX IF NOT EXISTS idx_incidents_status ON incidents(status);
CREATE INDEX IF NOT EXISTS idx_incidents_source_ip ON incidents(source_ip);
CREATE INDEX IF NOT EXISTS idx_detection_rule ON detection_events(rule_id);
CREATE INDEX IF NOT EXISTS idx_detection_incident ON detection_events(incident_id);
"""


def initialize_database(db_path: Optional[Union[str, Path]] = None) -> None:
    """Initialize all tables and bootstrap default administrator user if absent."""
    with get_db_connection(db_path) as conn:
        conn.executescript(SCHEMA_SQL)
        
        # Check if default admin user exists
        cursor = conn.cursor()
        cursor.execute("SELECT id FROM users WHERE username = ?", (INITIAL_ADMIN_USERNAME,))
        existing_admin = cursor.fetchone()
        
        if not existing_admin:
            hashed_pwd = hash_password(INITIAL_ADMIN_PASSWORD)
            cursor.execute(
                "INSERT INTO users (username, password_hash, role) VALUES (?, ?, ?)",
                (INITIAL_ADMIN_USERNAME, hashed_pwd, INITIAL_ADMIN_ROLE),
            )
            logger.info("Bootstrap initial admin user created: %s", INITIAL_ADMIN_USERNAME)


def reset_database(db_path: Optional[Union[str, Path]] = None) -> None:
    """Drop and re-initialize all tables. Used for administrative data reset."""
    with get_db_connection(db_path) as conn:
        cursor = conn.cursor()
        cursor.executescript("""
            DROP TABLE IF EXISTS incident_notes;
            DROP TABLE IF EXISTS detection_events;
            DROP TABLE IF EXISTS incidents;
            DROP TABLE IF EXISTS security_logs;
            DROP TABLE IF EXISTS users;
        """)
    initialize_database(db_path)
